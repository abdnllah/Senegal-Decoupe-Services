// Turns the brand SVG into a React component whose colours follow CSS
// (charcoal fills -> currentColor, orange fills -> accent), and copies the
// original to public/brand/logo.svg.
// Usage: node scripts/build-logo.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const logoDir = path.resolve(root, "..", "Logo");
const file = fs.readdirSync(logoDir).find((f) => f.toLowerCase().endsWith(".svg"));
const svg = fs.readFileSync(path.join(logoDir, file), "utf8");

fs.mkdirSync(path.join(root, "public", "brand"), { recursive: true });
fs.writeFileSync(path.join(root, "public", "brand", "logo.svg"), svg);

const shapes = [];
for (const m of svg.matchAll(/<(path|rect)\s([^>]*?)\/>/g)) {
  const [, tag, attrs] = m;
  const accent = /fill:#f36d2c/i.test(attrs);
  if (tag === "path") {
    const d = attrs.match(/(?:^|\s)d="([^"]+)"/)[1];
    shapes.push({ tag, accent, d });
  } else {
    const get = (k) => attrs.match(new RegExp(`(?:^|\\s)${k}="([^"]+)"`))[1];
    shapes.push({ tag, accent, x: get("x"), y: get("y"), width: get("width"), height: get("height") });
  }
}

fs.writeFileSync(
  path.join(root, "src", "components", "logo-shapes.generated.ts"),
  `// Generated by scripts/build-logo.mjs. Do not edit by hand.
export type LogoShape =
  | { tag: "path"; accent: boolean; d: string }
  | { tag: "rect"; accent: boolean; x: string; y: string; width: string; height: string };

export const logoShapes: LogoShape[] = ${JSON.stringify(shapes, null, 2)};
`,
);
console.log(`Logo: ${shapes.length} shapes`);
